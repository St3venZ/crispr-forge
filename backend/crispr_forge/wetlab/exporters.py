from Bio import SeqIO
from Bio.Seq import Seq
from Bio.SeqFeature import FeatureLocation, SeqFeature
from Bio.SeqRecord import SeqRecord
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from crispr_forge.models import DesignResponse
from crispr_forge.plasmids import resolve_plasmid_profile
from crispr_forge.verification.in_silico_pcr import find_primer_bindings


def _safe_locus_id(prefix: str, gene: str) -> str:
    clean = "".join(c if c.isalnum() or c == "_" else "_" for c in f"{prefix}_{gene}")
    return clean[:16]


def _serialize_gb(record: SeqRecord) -> bytes:
    buf = io.StringIO()
    SeqIO.write(record, buf, "genbank")
    return buf.getvalue().encode("utf-8")


def _add_primer_features(record: SeqRecord, seq_str: str, primers) -> None:
    """Attach exact in-silico-verified primer_bind annotations onto a GenBank SeqRecord."""
    for p in primers:
        hits = find_primer_bindings(seq_str, p.sequence, min_3p_anchor=15, max_anchor_mismatches=0)
        for h in hits:
            strand = 1 if h.strand == "+" else -1
            # Extend visual footprint to cover full binding length where inside bounds
            b_len = min(len(p.binding_region), len(seq_str))
            if strand == 1:
                start = max(0, h.template_end - b_len)
                end = h.template_end
            else:
                start = h.template_start
                end = min(len(seq_str), h.template_start + b_len)
            record.features.append(
                SeqFeature(
                    FeatureLocation(start, end, strand=strand),
                    type="primer_bind",
                    qualifiers={
                        "label": [p.name],
                        "note": [f"5'->3': {p.sequence} | Tm={p.tm_binding_c}C | {p.purification_method}"],
                    },
                )
            )


def export_genbank_wt(design: DesignResponse) -> bytes:
    """SnapGene-ready annotated GenBank map of the wild-type locus with deletion zone, homology arms, sgRNA, and primers."""
    locus = design.locus
    seq_str = locus.locus_sequence.upper()
    rec = SeqRecord(
        Seq(seq_str),
        id=_safe_locus_id("WT", locus.gene_name),
        name=_safe_locus_id("WT", locus.gene_name),
        description=f"CRISPR-Forge WT Locus: {locus.organism} {locus.gene_name} ({locus.accession}:{locus.slice_genome_start}..{locus.slice_genome_end})",
        annotations={
            "molecule_type": "DNA",
            "topology": "linear",
            "date": date.today().strftime("%d-%b-%Y").upper(),
            "organism": locus.organism,
            "comment": f"SHA256={locus.sequence_sha256}; Generated by CRISPR-Forge Zero-Trust Engine",
        },
    )

    # Neighbor CDS features
    for nb in locus.neighbor_genes:
        rec.features.append(
            SeqFeature(
                FeatureLocation(nb.rel_start, nb.rel_end, strand=1 if nb.strand == "+" else -1),
                type="CDS",
                qualifiers={
                    "gene": [nb.name],
                    "locus_tag": [nb.locus_tag or nb.name],
                    "product": [nb.product or "neighboring CDS"],
                    "label": [nb.name],
                },
            )
        )

    # Target CDS
    rec.features.append(
        SeqFeature(
            FeatureLocation(
                locus.target_rel_start,
                locus.target_rel_end,
                strand=1 if locus.strand == "+" else -1,
            ),
            type="CDS",
            qualifiers={
                "gene": [locus.gene_name],
                "locus_tag": [locus.locus_tag or locus.gene_name],
                "product": [locus.product],
                "label": [f"{locus.gene_name} (Target ORF)"],
            },
        )
    )

    # Planned deletion interval
    rec.features.append(
        SeqFeature(
            FeatureLocation(locus.deletion_rel_start, locus.deletion_rel_end, strand=1),
            type="misc_feature",
            qualifiers={
                "label": [f"Planned_Deletion ({locus.deleted_length_bp} bp)"],
                "note": [locus.safety_adjustment_note or "Scarless knockout deletion region"],
            },
        )
    )

    # Left and right homology arms
    la_start = seq_str.find(design.donor.left_arm_seq)
    ra_start = seq_str.find(design.donor.right_arm_seq, max(0, la_start))
    if la_start != -1:
        rec.features.append(
            SeqFeature(
                FeatureLocation(la_start, la_start + design.donor.left_arm_len, strand=1),
                type="misc_recomb",
                qualifiers={"label": [f"Left_Homology_Arm ({design.donor.left_arm_len} bp)"]},
            )
        )
    if ra_start != -1:
        rec.features.append(
            SeqFeature(
                FeatureLocation(ra_start, ra_start + design.donor.right_arm_len, strand=1),
                type="misc_recomb",
                qualifiers={"label": [f"Right_Homology_Arm ({design.donor.right_arm_len} bp)"]},
            )
        )

    # Selected sgRNA target + PAM
    sg = design.selected_sgrna
    if sg.strand == "+":
        sg_start = max(0, sg.cut_site_rel - 17)
        sg_end = min(len(seq_str), sg_start + 23)
    else:
        sg_start = max(0, sg.cut_site_rel - 6)
        sg_end = min(len(seq_str), sg_start + 23)
    rec.features.append(
        SeqFeature(
            FeatureLocation(sg_start, sg_end, strand=1 if sg.strand == "+" else -1),
            type="misc_binding",
            qualifiers={
                "label": [f"sgRNA_{sg.id} ({sg.pam})"],
                "note": [f"Spacer: {sg.spacer_20nt} | PAM: {sg.pam} | Score: {sg.on_target_score}"],
            },
        )
    )

    locus_primers = [
        p
        for p in design.all_primers
        if p.role in ("donor_left_arm", "donor_right_arm", "verify_outer", "verify_wt_internal", "sanger_seq")
    ]
    _add_primer_features(rec, seq_str, locus_primers)
    return _serialize_gb(rec)


def export_genbank_ko(design: DesignResponse) -> bytes:
    """SnapGene-ready annotated GenBank map of the in-silico recombined knockout locus."""
    locus = design.locus
    edited = design.verification_report.edited_locus_sequence.upper()
    rec = SeqRecord(
        Seq(edited),
        id=_safe_locus_id("KO", locus.gene_name),
        name=_safe_locus_id("KO", locus.gene_name),
        description=f"CRISPR-Forge Verified KO Locus: delta-{locus.gene_name} ({locus.organism})",
        annotations={
            "molecule_type": "DNA",
            "topology": "linear",
            "date": date.today().strftime("%d-%b-%Y").upper(),
            "organism": locus.organism,
            "comment": f"Edited SHA256={design.verification_report.edited_locus_sha256}; Deleted {locus.deleted_length_bp} bp",
        },
    )

    la_start = edited.find(design.donor.left_arm_seq)
    if la_start != -1:
        junc = la_start + design.donor.left_arm_len
        rec.features.append(
            SeqFeature(
                FeatureLocation(la_start, junc, strand=1),
                type="misc_recomb",
                qualifiers={"label": ["Left_Homology_Arm"]},
            )
        )
        rec.features.append(
            SeqFeature(
                FeatureLocation(junc, min(len(edited), junc + design.donor.right_arm_len), strand=1),
                type="misc_recomb",
                qualifiers={"label": ["Right_Homology_Arm"]},
            )
        )
        rec.features.append(
            SeqFeature(
                FeatureLocation(max(0, junc - 10), min(len(edited), junc + 10), strand=1),
                type="misc_feature",
                qualifiers={
                    "label": [f"Scarless_KO_Junction (-{locus.deleted_length_bp} bp)"],
                    "note": ["Verified Cas9 re-cut immune scarless deletion junction"],
                },
            )
        )

    # Shift surviving neighbor CDS coordinates cleanly onto edited sequence
    del_s, del_e = locus.deletion_rel_start, locus.deletion_rel_end
    delta = locus.deleted_length_bp
    for nb in locus.neighbor_genes:
        if nb.rel_end <= del_s:
            ns, ne = nb.rel_start, nb.rel_end
        elif nb.rel_start >= del_e:
            ns, ne = nb.rel_start - delta, nb.rel_end - delta
        else:
            continue
        if 0 <= ns < ne <= len(edited):
            rec.features.append(
                SeqFeature(
                    FeatureLocation(ns, ne, strand=1 if nb.strand == "+" else -1),
                    type="CDS",
                    qualifiers={"gene": [nb.name], "label": [nb.name]},
                )
            )

    ko_primers = [
        design.verification_primers.outer_forward,
        design.verification_primers.outer_reverse,
        design.verification_primers.sanger_primer,
    ]
    _add_primer_features(rec, edited, ko_primers)
    return _serialize_gb(rec)


def export_genbank_donor(design: DesignResponse) -> bytes:
    """SnapGene-ready annotated GenBank map of the assembled Donor DNA."""
    donor = design.donor
    seq_str = donor.full_donor_seq.upper()
    rec = SeqRecord(
        Seq(seq_str),
        id=_safe_locus_id("Donor", design.locus.gene_name),
        name=_safe_locus_id("Donor", design.locus.gene_name),
        description=f"CRISPR-Forge Donor DNA for delta-{design.locus.gene_name} ({donor.full_donor_len} bp)",
        annotations={
            "molecule_type": "DNA",
            "topology": "linear",
            "date": date.today().strftime("%d-%b-%Y").upper(),
            "organism": design.locus.organism,
        },
    )
    rec.features.append(
        SeqFeature(
            FeatureLocation(0, donor.left_arm_len, strand=1),
            type="misc_recomb",
            qualifiers={"label": [f"Left_Arm ({donor.left_arm_len} bp)"]},
        )
    )
    rec.features.append(
        SeqFeature(
            FeatureLocation(donor.left_arm_len, donor.full_donor_len, strand=1),
            type="misc_recomb",
            qualifiers={"label": [f"Right_Arm ({donor.right_arm_len} bp)"]},
        )
    )
    ov_idx = seq_str.find(donor.overlap_seq)
    if ov_idx != -1:
        rec.features.append(
            SeqFeature(
                FeatureLocation(ov_idx, ov_idx + donor.overlap_len, strand=1),
                type="misc_feature",
                qualifiers={"label": [f"OE_PCR_Overlap ({donor.overlap_len} bp, Tm={donor.overlap_tm_c}C)"]},
            )
        )
    _add_primer_features(rec, seq_str, donor.primers)
    return _serialize_gb(rec)


def export_genbank_plasmid(design: DesignResponse) -> bytes:
    """SnapGene-ready GenBank map of the verified sgRNA expression cassette inside the chosen plasmid."""
    profile = resolve_plasmid_profile(design.plasmid_system, design.custom_plasmid)
    cassette = design.verification_report.plasmid_assembled_cassette.upper()
    if not cassette:
        cassette = (
            profile.promoter_upstream_seq
            + design.selected_sgrna.spacer_20nt.upper()
            + profile.scaffold_downstream_seq
        )
    rec = SeqRecord(
        Seq(cassette),
        id=_safe_locus_id("sgRNA", design.locus.gene_name),
        name=_safe_locus_id("sgRNA", design.locus.gene_name),
        description=f"CRISPR-Forge Verified sgRNA Expression Cassette ({profile.short_label}) targeting {design.locus.gene_name}",
        annotations={
            "molecule_type": "DNA",
            "topology": "linear",
            "date": date.today().strftime("%d-%b-%Y").upper(),
            "organism": "Synthetic construct",
        },
    )
    prom_len = len(profile.promoter_upstream_seq)
    sp_end = prom_len + 20
    rec.features.append(
        SeqFeature(
            FeatureLocation(0, prom_len, strand=1),
            type="promoter",
            qualifiers={"label": [f"sgRNA_Promoter ({profile.short_label})"]},
        )
    )
    rec.features.append(
        SeqFeature(
            FeatureLocation(prom_len, min(len(cassette), sp_end), strand=1),
            type="misc_binding",
            qualifiers={
                "label": [f"N20_Spacer_{design.locus.gene_name}"],
                "note": [f"5'->3': {design.selected_sgrna.spacer_20nt} | PAM={design.selected_sgrna.pam}"],
            },
        )
    )
    rec.features.append(
        SeqFeature(
            FeatureLocation(min(len(cassette), sp_end), len(cassette), strand=1),
            type="misc_RNA",
            qualifiers={"label": ["SpCas9_gRNA_Scaffold_Terminator"]},
        )
    )
    return _serialize_gb(rec)


def export_primers_xlsx(design: DesignResponse) -> bytes:
    """Generate a Sangon (生工) / Tsingke (擎科) ready Excel primer order workbook with verification summary."""
    wb = Workbook()

    # Sheet 1: Primer Order Table
    ws = wb.active
    ws.title = "引物订购单"
    headers = [
        "引物名称 (Primer Name)",
        "序列 (5'->3')",
        "长度 (nt)",
        "建议纯化方式",
        "Tm_结合区 (°C)",
        "GC (%)",
        "发夹 ΔG",
        "角色分类",
        "实验备注",
    ]
    ws.append(headers)

    header_fill = PatternFill("solid", fgColor="0F766E")
    header_font = Font(name="Microsoft YaHei", size=10, bold=True, color="FFFFFF")
    mono_font = Font(name="Consolas", size=10)
    body_font = Font(name="Microsoft YaHei", size=10)
    page_fill = PatternFill("solid", fgColor="FEF3C7")
    page_font = Font(name="Microsoft YaHei", size=10, bold=True, color="B45309")
    zebra_fill = PatternFill("solid", fgColor="F8FAFC")
    thin_border = Border(
        left=Side(style="thin", color="E2E8F0"),
        right=Side(style="thin", color="E2E8F0"),
        top=Side(style="thin", color="E2E8F0"),
        bottom=Side(style="thin", color="E2E8F0"),
    )

    for col_idx in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col_idx)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = thin_border
    ws.row_dimensions[1].height = 26

    role_labels = {
        "sgRNA_cloning": "sgRNA 克隆 Oligo",
        "donor_left_arm": "Donor 左同源臂",
        "donor_right_arm": "Donor 右同源臂",
        "verify_outer": "跨位点外侧验证",
        "verify_wt_internal": "WT 内部阴性对照",
        "sanger_seq": "Sanger 测序确认",
        "plasmid_verify": "质粒菌落验证",
    }

    for row_idx, p in enumerate(design.all_primers, start=2):
        ws.append(
            [
                p.name,
                p.sequence,
                p.length_nt,
                p.purification_method,
                p.tm_binding_c,
                p.gc_percent,
                p.hairpin_dg,
                role_labels.get(p.role, p.role),
                p.notes,
            ]
        )
        is_zebra = row_idx % 2 == 1
        for col_idx in range(1, len(headers) + 1):
            c = ws.cell(row=row_idx, column=col_idx)
            c.border = thin_border
            c.font = mono_font if col_idx == 2 else body_font
            if is_zebra:
                c.fill = zebra_fill
            if col_idx in (3, 4, 5, 6, 7):
                c.alignment = Alignment(horizontal="center", vertical="center")
            else:
                c.alignment = Alignment(horizontal="left", vertical="center")
        if p.purification_method == "PAGE":
            pur_cell = ws.cell(row=row_idx, column=4)
            pur_cell.fill = page_fill
            pur_cell.font = page_font
        ws.row_dimensions[row_idx].height = 22

    # Auto-fit column widths
    for col_idx in range(1, len(headers) + 1):
        max_len = max(len(str(ws.cell(row=r, column=col_idx).value or "")) for r in range(1, ws.max_row + 1))
        ws.column_dimensions[get_column_letter(col_idx)].width = min(max(max_len + 4, 12), 68)

    # Sheet 2: Verification & Design Summary
    ws2 = wb.create_sheet(title="零信任验证摘要")
    vr = design.verification_report
    summary_rows = [
        ("项目平台", "CRISPR-Forge 零信任原核 CRISPR/Cas9 全自动设计平台"),
        ("目标菌株", f"{design.locus.organism} ({design.locus.accession})"),
        ("目标基因", f"{design.locus.gene_name} ({design.locus.locus_tag}) — {design.locus.product}"),
        ("质粒体系", design.plasmid_system),
        ("零信任认证结果", f"{vr.overall_status} ({vr.passed_count} PASS / {vr.warn_count} WARN / {vr.fail_count} FAIL)"),
        ("序列 SHA-256 溯源", design.locus.sequence_sha256),
        ("选中 sgRNA", f"5'-{design.selected_sgrna.spacer_20nt}-3' (PAM: {design.selected_sgrna.pam}, 评分: {design.selected_sgrna.on_target_score})"),
        ("WT vs KO 菌落 PCR 条带", f"WT = {design.verification_primers.wt_amplicon_bp} bp | KO = {design.verification_primers.ko_amplicon_bp} bp (差值 {design.verification_primers.band_diff_bp} bp)"),
    ]
    for r_i, (k, v) in enumerate(summary_rows, start=1):
        ws2.cell(row=r_i, column=1, value=k).font = Font(name="Microsoft YaHei", size=10, bold=True)
        ws2.cell(row=r_i, column=2, value=v).font = Font(name="Microsoft YaHei", size=10)

    ws2.append([])
    ws2.append(["检查项 ID", "检查名称", "状态", "验证结果摘要"])
    hdr_row = ws2.max_row
    for c_i in range(1, 5):
        cell = ws2.cell(row=hdr_row, column=c_i)
        cell.fill = header_fill
        cell.font = header_font
    for chk in vr.checks:
        ws2.append([chk.check_id, chk.name, chk.status, chk.summary])

    ws2.column_dimensions["A"].width = 26
    ws2.column_dimensions["B"].width = 34
    ws2.column_dimensions["C"].width = 12
    ws2.column_dimensions["D"].width = 76

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def export_sop_markdown(design: DesignResponse) -> bytes:
    """Generate a clean, printable laboratory SOP Markdown document."""
    locus = design.locus
    sg = design.selected_sgrna
    vr = design.verification_report
    vp = design.verification_primers
    wp = design.wetlab_protocol

    lines = [
        f"# CRISPR-Forge 零信任基因敲除实验操作手册 (SOP) — Δ{locus.gene_name}",
        "",
        f"- **目标菌株**：{locus.organism} (`{locus.accession}`)",
        f"- **目标基因**：`{locus.gene_name}` (`{locus.locus_tag}`) — {locus.product}",
        f"- **质粒体系**：`{design.plasmid_system}` | **聚合酶**：`{wp.polymerase}`",
        f"- **零信任验证状态**：**{vr.overall_status}**（{vr.passed_count}/{vr.total_checks} PASS, {vr.warn_count} WARN, {vr.fail_count} FAIL）",
        f"- **序列溯源 SHA-256**：`{locus.sequence_sha256}`",
        "",
        "## 1. AI 专家设计简报",
        "",
        design.agent_summary,
        "",
        "## 2. 12 点零信任 *In Silico* 硅片验证清单",
        "",
        "| 编号 | 检查项 | 状态 | 校验摘要 |",
        "| :--- | :--- | :--- | :--- |",
    ]
    for chk in vr.checks:
        lines.append(f"| `{chk.check_id}` | {chk.name} | **{chk.status}** | {chk.summary} |")

    lines.extend(
        [
            "",
            "## 3. 选中 sgRNA 与全部订购引物表",
            "",
            f"- **20-nt Spacer**：`5'-{sg.spacer_20nt}-3'`（PAM：`{sg.pam}`，链向：`{sg.strand}`，切点坐标：`{sg.cut_site_genome}`）",
            f"- **脱靶扫描结论**：{sg.off_target_summary}",
            "",
            "| 引物名称 | 序列 (5'->3') | 长度 (nt) | 纯化 | Tm (°C) | 备注 |",
            "| :--- | :--- | :---: | :---: | :---: | :--- |",
        ]
    )
    for p in design.all_primers:
        lines.append(
            f"| `{p.name}` | `{p.sequence}` | {p.length_nt} | {p.purification_method} | {p.tm_binding_c} | {p.notes} |"
        )

    lines.extend(
        [
            "",
            "## 4. 预期琼脂糖凝胶电泳条带对照",
            "",
            f"- **野生型菌落 PCR (VF+VR)**：`{vp.wt_amplicon_bp} bp`",
            f"- **阳性敲除株菌落 PCR (VF+VR)**：`{vp.ko_amplicon_bp} bp`（缩短 `{vp.band_diff_bp} bp`）",
            f"- **外侧安全距离**：VF 距左臂外侧 `{vp.distance_outside_la_bp} bp`，VR 距右臂外侧 `{vp.distance_outside_ra_bp} bp`",
            "",
            "## 5. 动态移液体系与 PCR 扩增程序",
            "",
        ]
    )
    for rxn in wp.reactions:
        lines.append(f"### {rxn.title}（总体积 {rxn.total_volume_ul} μL）")
        if rxn.subtitle:
            lines.append(f"> {rxn.subtitle}")
        lines.append("")
        lines.append("| 试剂组分 | 母液浓度 | 加样量 (μL) | 终量 / 备注 |")
        lines.append("| :--- | :---: | :---: | :--- |")
        for comp in rxn.components:
            note_col = comp.final_amount
            if comp.dilution_alert:
                note_col += f" — **⚠️ {comp.dilution_alert}**"
            lines.append(f"| {comp.reagent} | {comp.stock_conc} | **{comp.volume_ul}** | {note_col} |")
        if rxn.thermocycler_program:
            lines.append("")
            lines.append("**PCR / 反应程序**：")
            for step in rxn.thermocycler_program:
                lines.append(f"- {step}")
        lines.append("")

    lines.extend(["## 6. 4 天标准湿实验执行时间线", ""])
    for day in wp.timeline:
        lines.append(f"### {day.day}：{day.title}")
        for st in day.steps:
            lines.append(f"- {st}")
        lines.append(f"- **关键质控节点**：{day.checkpoint}")
        lines.append("")

    return "\n".join(lines).encode("utf-8")


def export_bundle_zip(design: DesignResponse) -> bytes:
    """Package all 4 SnapGene .gb maps, Sangon/Tsingke .xlsx, Markdown SOP, and JSON audit report into one ZIP."""
    gene = design.locus.gene_name
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{gene}_01_WT_locus.gb", export_genbank_wt(design))
        zf.writestr(f"{gene}_02_KO_edited_locus.gb", export_genbank_ko(design))
        zf.writestr(f"{gene}_03_Donor_DNA.gb", export_genbank_donor(design))
        zf.writestr(f"{gene}_04_sgRNA_plasmid_cassette.gb", export_genbank_plasmid(design))
        zf.writestr(f"{gene}_primers_order.xlsx", export_primers_xlsx(design))
