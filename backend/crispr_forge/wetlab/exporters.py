def export_artifact(design: DesignResponse, fmt: str) -> tuple[bytes, str, str]:
    """Unified exporter returning (bytes_payload, media_type, suggested_filename)."""
    gene = "".join(c if c.isalnum() or c in ("_", "-") else "_" for c in design.locus.gene_name)
    mapping = {
        "gb_wt": (export_genbank_wt, "chemical/x-genbank", f"{gene}_WT_locus.gb"),
        "gb_ko": (export_genbank_ko, "chemical/x-genbank", f"{gene}_KO_edited.gb"),
        "gb_donor": (export_genbank_donor, "chemical/x-genbank", f"{gene}_Donor_DNA.gb"),
        "gb_plasmid": (export_genbank_plasmid, "chemical/x-genbank", f"{gene}_sgRNA_cassette.gb"),
        "primers_xlsx": (
            export_primers_xlsx,
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            f"{gene}_primers_order.xlsx",
        ),
        "sop_md": (export_sop_markdown, "text/markdown; charset=utf-8", f"{gene}_wetlab_SOP.md"),
        "bundle_zip": (export_bundle_zip, "application/zip", f"{gene}_CRISPR_Forge_BenchPack.zip"),
    }
    if fmt not in mapping:
        raise ValueError(f"不支持的导出格式: {fmt}。可选: {', '.join(mapping.keys())}")
    fn, mime, fname = mapping[fmt]
    return fn(design), mime, fname
